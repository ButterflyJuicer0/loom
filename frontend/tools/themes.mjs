// Loom's themes, the tokens of each. A theme's tokens are one file,
// tools/themes/<id>.json: its name, where it comes in Settings' list, its
// font, and a shadcn/ui preset (as tweakcn exports them) for light and dark.
//
//   node tools/themes.mjs            every theme
//   node tools/themes.mjs celeste    one
//
// For each it writes, beside the theme's own stylesheet:
//
//   src/themes/<id>.tokens.css   shadcn/ui's tokens (--background, --primary,
//                                --radius …) per appearance, plus the few Loom
//                                derives from them (its font, its shadow, its
//                                quiet text)
//   src/themes/<id>.meta.json    what Settings shows of it
//
// How the tokens reach the interface is in src/themes.css. A theme touches no
// file but its own, so several can be worked on at once.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, "../src/themes")
const wanted = process.argv.slice(2)
const ids = wanted.length
  ? wanted
  : fs.readdirSync(path.join(here, "themes")).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5))

const COLOURS = [
  "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
  "primary", "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground",
  "accent", "accent-foreground", "destructive", "border", "input", "ring",
  "sidebar", "sidebar-foreground", "sidebar-primary", "sidebar-primary-foreground",
  "sidebar-accent", "sidebar-accent-foreground", "sidebar-border", "sidebar-ring",
]

// tweakcn's shadow is five numbers and a colour; a preset without them gets
// shadcn/ui's own soft one.
function shadow(s) {
  const x = s["shadow-offset-x"] ?? "0px"
  const y = s["shadow-offset-y"] ?? "1px"
  const blur = s["shadow-blur"] ?? "3px"
  const spread = s["shadow-spread"] ?? "0px"
  const colour = s["shadow-color"] ?? "hsl(0 0% 0%)"
  const opacity = Number(s["shadow-opacity"] ?? "0.1")
  // An opacity of 0 is tweakcn's "the colour carries its own alpha".
  const tint = opacity > 0 && opacity < 1 ? `color-mix(in srgb, ${colour} ${Math.round(opacity * 100)}%, transparent)` : colour
  return `${x} ${y} ${blur} ${spread} ${tint}`
}

// ── Legibility ──────────────────────────────────────────────────────────
// A preset is taken as it is, except where its text would be hard to read in
// Loom: WCAG contrast, on hex colours (anything else is left alone).
const rgb = (hex) => (/^#[0-9a-f]{6}$/i.test(hex) ? [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255) : null)
const hex = (c) => "#" + c.map((v) => Math.round(v * 255).toString(16).padStart(2, "0")).join("")
const luminance = (c) => {
  const [r, g, b] = c.map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}
const mix = (a, b, p) => a.map((v, i) => v * p + b[i] * (1 - p))

// Text on a filled surface (the send button, a chosen segment, a user's
// bubble): the preset's own colour if it reads, else near-black or white.
function onFill(text, fill, least) {
  const [t, f] = [rgb(text), rgb(fill)]
  if (!t || !f || contrast(t, f) >= least) return text
  return ["#111111", "#ffffff"].sort((a, b) => contrast(rgb(b), f) - contrast(rgb(a), f))[0]
}

// Loom's quiet text: the text colour mixed towards the page, as little as
// still reads on both the page and the sidebar.
function dim(s) {
  // A sidebar with a text colour of its own (dark wall, light page) is read
  // in that colour, not this one.
  const ownSidebar = s["sidebar-foreground"] && s["sidebar-foreground"] !== s.foreground
  const [fg, bg, side] = [rgb(s.foreground), rgb(s.background), rgb(ownSidebar ? s.background : (s.sidebar ?? s.background))]
  if (!fg || !bg || !side) return null
  for (let p = 0.6; p <= 1.0001; p += 0.02) {
    const c = mix(fg, bg, p)
    if (contrast(c, bg) >= 4.5 && contrast(c, side) >= 4.2) return hex(c)
  }
  return s.foreground
}

for (const id of ids) {
  // `font` is which of Loom's own stacks the interface is set in (sans, serif,
  // rounded, mono, hand, pixel); `outline` is how wide the theme draws its
  // outlines (1px unless said).
  const theme = JSON.parse(fs.readFileSync(path.join(here, `themes/${id}.json`), "utf8"))
  const light = theme.styles.light
  // A preset's dark half only says what differs.
  const modes = { light, dark: { ...light, ...theme.styles.dark } }
  const swatches = {}
  let css = `/* Generated by tools/themes.mjs from tools/themes/${id}.json. Do not edit:
   change the tokens there and run the script again. */\n`

  for (const [mode, preset] of Object.entries(modes)) {
    const s = {
      ...preset,
      "primary-foreground": onFill(preset["primary-foreground"], preset.primary, 3.5),
      "secondary-foreground": onFill(preset["secondary-foreground"], preset.secondary, 4.5),
    }
    const lines = COLOURS.filter((k) => s[k]).map((k) => `  --${k}: ${s[k]};`)
    const quiet = dim(s)
    if (quiet) lines.push(`  --dim: ${quiet};`)
    lines.push(`  --radius: ${s.radius ?? "0.5rem"};`)
    lines.push(`  --raised: ${shadow(s)};`)
    lines.push(`  --ui: var(--font-${theme.font ?? "sans"});`)
    if (theme.outline) lines.push(`  --bw: ${theme.outline}px;`)
    if (s["letter-spacing"] && s["letter-spacing"] !== "0em") lines.push(`  --tracking: ${s["letter-spacing"]};`)
    css += `\n:root[data-style="${id}"][data-theme="${mode}"] {\n${lines.join("\n")}\n}\n`
    swatches[mode] = {
      background: s.background,
      foreground: s.foreground,
      sidebar: s.sidebar ?? s.background,
      card: s.card,
      bubble: s.secondary,
      primary: s.primary,
      border: s.border,
    }
  }

  fs.writeFileSync(path.join(out, `${id}.tokens.css`), css)
  fs.writeFileSync(
    path.join(out, `${id}.meta.json`),
    JSON.stringify({ id, order: theme.order ?? 100, name: theme.name, blurb: theme.blurb, radius: light.radius ?? "0.5rem", ...swatches }, null, 2) + "\n",
  )
  console.log(`${id} → src/themes/${id}.tokens.css, ${id}.meta.json`)
}
